#!/usr/bin/env python3
"""Generate the CLI reference page from the pinned help snapshot.

Reads tests/snapshots/help.txt (precommit-pinned `icarium --help`)
and writes site/content/docs/cli.md. Re-run after any CLI change:

    python3 site/scripts/gen-cli.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "site", "content", "docs", "cli.md")

PROSE = """---
title: CLI reference
weight: 10
---

`check` is the main entry point: it reads an elaborated netlist
from `scripts/elaborate.sh` (`--yosys-json`) plus an optional
SDC file (`--sdc`). `domains`, `resets`, and `crossings` read
the same inputs to expose the intermediate models for debugging —
which flop belongs to which clock, which reset releases it,
and which signal paths cross domains. `stats` takes the
netlist alone, `clocks` takes only an SDC file, `rules`
documents the catalog without inputs, and `import-meridian`
converts Tcl waiver files.

## Exit codes

| Code | Meaning                                            |
| ---- | -------------------------------------------------- |
| 0    | clean (or a map-only/info command finished)        |
| 1    | error-severity findings present; report printed    |
| 2    | bad arguments                                      |
| 3    | I/O or internal error                              |

## Output formats (`check --format`)

| Format | Shape                                              |
| ------ | -------------------------------------------------- |
| text   | grouped human report (default)                     |
| ids    | one rule id per finding, for diffing               |
| json   | versioned findings schema                          |
| sarif  | SARIF 2.1.0 for code-scanning dashboards           |
| toon   | token-efficient tabular emit                       |

## Streaming large designs

`crossings` and `check` accept `--stream --stream-chunk N
--pair-budget M --progress`: the walker consumes each chunk
through the rules and keeps only findings, so billion-pair
designs fit in RAM. Chunk edges snap to cell runs, so
streamed output matches the materialized run.

## Full help

```text
"""

TAIL = """```

The dump above is pinned by `tests/snapshots/help.txt` and
regenerated by `site/scripts/gen-cli.py`.
"""


def main():
    help_text = open(os.path.join(ROOT, "tests", "snapshots", "help.txt")).read().rstrip()
    with open(OUT, "w") as f:
        f.write(PROSE + help_text + "\n" + TAIL)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
